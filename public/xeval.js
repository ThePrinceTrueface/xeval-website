/**
 * xeval — Dynamic script, HTML & CSS injection library with template engine
 * @version 5.1.0
 */

// ─────────────────────────────────────────────
//  Constants
// ─────────────────────────────────────────────

const XEVAL_TAG        = '[xeval]'
const XEVAL_KEY_ATTR   = 'data-xeval-key'


// ─────────────────────────────────────────────
//  Utilities
// ─────────────────────────────────────────────

/**
 * Generate a unique injection key using crypto.randomUUID()
 * @returns {string}
 */
function generateKey() {
    return crypto.randomUUID()
}

/**
 * Detect engine type from a URL extension
 * @param {string} url
 * @returns {'js' | 'html' | 'css' | null}
 */
function detectTypeFromUrl(url) {
    const clean = url.split('?')[0].split('#')[0]
    if (clean.endsWith('.html') || clean.endsWith('.htm')) return 'html'
    if (clean.endsWith('.js')   || clean.endsWith('.mjs')) return 'js'
    if (clean.endsWith('.css'))                            return 'css'
    return null
}

/**
 * Resolve a DOM target from a CSS selector, an Element instance,
 * or a fallback element (document.body by default)
 * @param {string | Element | null | undefined} target
 * @param {Element} [fallback]
 * @returns {Element}
 */
function resolveTarget(target, fallback = document.body) {
    if (!target) return fallback

    if (target instanceof Element) return target

    const el = document.querySelector(target)
    if (!el) {
        console.warn(`${XEVAL_TAG} target "${target}" not found in DOM — falling back to ${fallback.tagName.toLowerCase()}`)
        return fallback
    }

    return el
}


// ─────────────────────────────────────────────
//  CoreEngine — shared base for all engines
// ─────────────────────────────────────────────

class CoreEngine {

    #source
    // Map<key, Element> — tracks every injection made by this engine instance
    #keyRegistry = new Map()

    /**
     * @param {string} source
     */
    constructor(source) {
        if (typeof source !== 'string') {
            throw new TypeError(`${XEVAL_TAG} CoreEngine expects a string, got: ${typeof source}`)
        }
        this.#source = source
    }

    // ── Interpolation ──────────────────────────

    /**
     * Interpolates $$key placeholders with context values
     * Supports: primitives, arrays, objects (JSON), functions
     * @param {string} template
     * @param {object} [context]
     * @returns {string}
     */
    _interpolate(template, context) {
        if (!context || typeof context !== 'object') return template

        const placeholderRegexp = /\$\$(\w+)/g

        return template.replaceAll(placeholderRegexp, (match, key) => {
            if (!(key in context)) return match

            const value = context[key]

            if (typeof value === 'function') {
                const fnStr = value.toString()
                const isArrow = fnStr.includes('=>')
                const serializedFn = isArrow
                    ? fnStr
                    : fnStr.replace(/^function\s*\w*\s*/, '').replace(/^/, '() => ')
                return `const ${key} = ${serializedFn}`
            }

            if (typeof value === 'object') {
                return JSON.stringify(value)
            }

            return String(value)
        })
    }

    // ── Key & Registry ─────────────────────────

    /**
     * Stamp an element with a unique data-xeval-key and register it
     * @param {Element} el
     * @returns {string} the generated key
     */
    _stamp(el) {
        const key = generateKey()
        el.setAttribute(XEVAL_KEY_ATTR, key)
        this.#keyRegistry.set(key, el)
        return key
    }

    /**
     * Retrieve an injected element by its xeval key (internal)
     * @param {string} key
     * @returns {Element | null}
     */
    _getByKey(key) {
        return this.#keyRegistry.get(key) ?? null
    }

    /**
     * Retrieve an injected element by its xeval key (public API)
     * @param {string} key
     * @returns {Element | null}
     */
    getByKey(key) {
        return this._getByKey(key)
    }

    /**
     * The key of the last element injected by this engine instance
     * @returns {string | null}
     */
    get lastKey() {
        const keys = [...this.#keyRegistry.keys()]
        return keys.at(-1) ?? null
    }

    /**
     * The last element injected by this engine instance
     * @returns {Element | null}
     */
    get lastInjected() {
        return this.lastKey ? this._getByKey(this.lastKey) : null
    }

    /**
     * All keys generated by this engine instance, in injection order
     * @returns {string[]}
     */
    get keys() {
        return [...this.#keyRegistry.keys()]
    }

    // ── Cleanup ────────────────────────────────

    /**
     * Remove a single injected element by its xeval key
     * @param {string} key
     * @returns {boolean} true if the element was found and removed, false otherwise
     */
    cleanupOne(key) {
        const el = this._getByKey(key)
        if (!el) {
            console.warn(`${XEVAL_TAG} cleanupOne() — no element found for key "${key}"`)
            return false
        }
        el.remove()
        this.#keyRegistry.delete(key)
        return true
    }

    /**
     * Remove all elements injected by this engine instance from the DOM
     */
    cleanup() {
        for (const el of this.#keyRegistry.values()) {
            el.remove()
        }
        this.#keyRegistry.clear()
    }

    // ── Source access ──────────────────────────

    /**
     * Return the interpolated source without injecting anything into the DOM
     * @param {{ context?: object }} [options]
     * @returns {string}
     */
    render(options = {}) {
        return this._interpolate(this.#source, options.context)
    }

    /**
     * The raw original source before any interpolation
     * @returns {string}
     */
    get rawSource() {
        return this.#source
    }

    /**
     * Internal source accessor for subclasses
     * @returns {string}
     */
    get _source() {
        return this.#source
    }
}


// ─────────────────────────────────────────────
//  ScriptEngine — JS injection
// ─────────────────────────────────────────────

class ScriptEngine extends CoreEngine {

    /**
     * Interpolate and inject the script into the DOM
     * @param {{
     *   context?: object,
     *   module?:  boolean,
     *   id?:      string,
     *   target?:  string | Element
     * }} [options]
     * @returns {HTMLScriptElement} the injected script element (carries data-xeval-key)
     */
    run(options = {}) {
        const { context, module: asModule = false, id, target } = options

        const interpolatedCode = this._interpolate(this._source, context)
        const container = resolveTarget(target, document.body)

        const script = document.createElement('script')
        if (asModule) script.type = 'module'
        if (id) script.id = id
        script.textContent = interpolatedCode

        // stamp before appending so the attribute is present when the script runs
        this._stamp(script)
        container.appendChild(script)

        return script
    }

    /**
     * Alias for run()
     */
    inject(options = {}) {
        return this.run(options)
    }

    // NOTE: update() is intentionally not implemented on ScriptEngine.
    // Modifying a <script> element's textContent after execution has no effect
    // in any browser — the code is already parsed and run.
    // To re-run with new context, use: engine.cleanup() then engine.run()
}


// ─────────────────────────────────────────────
//  HtmlEngine — HTML injection
// ─────────────────────────────────────────────

/**
 * @typedef {'append' | 'prepend' | 'before' | 'after' | 'replace'} InsertPosition
 */

class HtmlEngine extends CoreEngine {

    /**
     * Interpolate and inject HTML into the DOM
     * @param {{
     *   context?:  object,
     *   target?:   string | Element,
     *   position?: InsertPosition,
     *   safe?:     boolean,
     *   id?:       string,
     *   class?:    string
     * }} [options]
     * @returns {HTMLDivElement} the injected wrapper element (carries data-xeval-key)
     */
    run(options = {}) {
        const {
            context,
            target,
            position = 'append',
            safe = false,
            id,
            class: className
        } = options

        const interpolatedHTML = this._interpolate(this._source, context)
        const container = resolveTarget(target, document.body)

        const wrapper = document.createElement('div')
        this._applyContent(wrapper, interpolatedHTML, safe)

        if (id) wrapper.id = id
        if (className) wrapper.className = className

        this._stamp(wrapper)
        this._insert(wrapper, container, position)

        return wrapper
    }

    /**
     * Update the content of an injected wrapper element
     * Resolves target in this order: key → id → lastInjected
     * @param {{
     *   context?: object,
     *   safe?:    boolean,
     *   key?:     string,
     *   id?:      string
     * }} [options]
     * @returns {Element | null} the updated element, or null if not found
     */
    update(options = {}) {
        const { context, safe = false, key, id } = options

        const target = key
            ? this._getByKey(key)
            : id
                ? document.getElementById(id)
                : this.lastInjected

        if (!target) {
            console.warn(`${XEVAL_TAG} HtmlEngine.update() — no injected element found to update`)
            return null
        }

        const interpolatedHTML = this._interpolate(this._source, context)
        this._applyContent(target, interpolatedHTML, safe)

        return target
    }

    /**
     * Apply content to an element using innerHTML or textContent based on safe mode
     * @param {Element} el
     * @param {string} content
     * @param {boolean} safe
     */
    _applyContent(el, content, safe) {
        if (safe) {
            el.textContent = content
        } else {
            el.innerHTML = content
        }
    }

    /**
     * Insert an element relative to a container based on position
     * @param {Element} el
     * @param {Element} container
     * @param {InsertPosition} position
     */
    _insert(el, container, position) {
        switch (position) {
            case 'append':
                container.appendChild(el)
                break
            case 'prepend':
                container.insertBefore(el, container.firstChild)
                break
            case 'before':
                container.parentNode?.insertBefore(el, container)
                break
            case 'after':
                container.parentNode?.insertBefore(el, container.nextSibling)
                break
            case 'replace':
                container.innerHTML = ''
                container.appendChild(el)
                break
            default:
                console.warn(`${XEVAL_TAG} unknown position "${position}" — falling back to append`)
                container.appendChild(el)
        }
    }

    /**
     * Alias for run()
     */
    inject(options = {}) {
        return this.run(options)
    }
}


// ─────────────────────────────────────────────
//  CSSEngine — CSS injection
// ─────────────────────────────────────────────

class CSSEngine extends CoreEngine {

    /**
     * Interpolate and inject CSS into the DOM as a <style> element
     * @param {{
     *   context?: object,
     *   target?:  string | Element,
     *   id?:      string,
     *   media?:   string
     * }} [options]
     * @returns {HTMLStyleElement} the injected style element (carries data-xeval-key)
     */
    run(options = {}) {
        const { context, target, id, media } = options

        const interpolatedCSS = this._interpolate(this._source, context)
        const container = resolveTarget(target, document.head)

        const styleEl = document.createElement('style')
        styleEl.textContent = interpolatedCSS
        if (id) styleEl.id = id
        if (media) styleEl.media = media

        this._stamp(styleEl)
        container.appendChild(styleEl)

        return styleEl
    }

    /**
     * Update the content of an injected <style> element
     * Resolves target in this order: key → id → lastInjected
     * @param {{
     *   context?: object,
     *   key?:     string,
     *   id?:      string
     * }} [options]
     * @returns {HTMLStyleElement | null} the updated element, or null if not found
     */
    update(options = {}) {
        const { context, key, id } = options

        const target = key
            ? this._getByKey(key)
            : id
                ? document.getElementById(id)
                : this.lastInjected

        if (!target) {
            console.warn(`${XEVAL_TAG} CSSEngine.update() — no injected <style> found to update`)
            return null
        }

        target.textContent = this._interpolate(this._source, context)

        return target
    }

    /**
     * Alias for run()
     */
    inject(options = {}) {
        return this.run(options)
    }
}


// ─────────────────────────────────────────────
//  Xeval — main entry point (singleton)
// ─────────────────────────────────────────────

class Xeval {

    /**
     * Prepare a JS script from a raw source string
     * @param {string} source
     * @returns {ScriptEngine}
     */
    prepare(source) {
        return new ScriptEngine(source)
    }

    /**
     * Prepare an HTML template from a raw source string
     * @param {string} source
     * @returns {HtmlEngine}
     */
    prepareHTML(source) {
        return new HtmlEngine(source)
    }

    /**
     * Prepare a CSS stylesheet from a raw source string
     * @param {string} source
     * @returns {CSSEngine}
     */
    prepareCSS(source) {
        return new CSSEngine(source)
    }

    /**
     * Load a JS, HTML, or CSS file from a remote URL.
     * Type is auto-detected from the file extension (.js, .mjs, .html, .htm, .css).
     * Pass { type } explicitly when the URL has no recognizable extension.
     * @param {string} url
     * @param {{ type?: 'js' | 'html' | 'css' }} [options]
     * @returns {Promise<ScriptEngine | HtmlEngine | CSSEngine>}
     */
    async loadFrom(url, options = {}) {
        const resolvedType = options.type ?? detectTypeFromUrl(url)

        if (!resolvedType) {
            throw new Error(
                `${XEVAL_TAG} cannot detect file type from "${url}". ` +
                `Pass { type: 'js' }, { type: 'html' }, or { type: 'css' } explicitly.`
            )
        }

        try {
            const response = await globalThis.fetch(url)

            if (!response.ok) {
                throw new Error(
                    `${XEVAL_TAG} failed to load "${url}": ${response.status} ${response.statusText}`
                )
            }

            const source = await response.text()

            if (resolvedType === 'html') return new HtmlEngine(source)
            if (resolvedType === 'css')  return new CSSEngine(source)
            return new ScriptEngine(source)

        } catch (err) {
            console.error(`${XEVAL_TAG} loadFrom error:`, err)
            throw err
        }
    }
}

export default new Xeval()
